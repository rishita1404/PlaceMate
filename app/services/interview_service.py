"""
app/services/interview_service.py
──────────────────────────────────
Interview question retrieval and (optionally) AI generation.

Returns questions in three clearly separated buckets:
  1. source_backed  — questions from the verified dataset with a source URL.
  2. ai_generated   — practice questions generated by Gemini from job context.
  3. unverified     — community-submitted questions without source verification.

AI-generated questions are NEVER labeled as real historical questions.
The disclaimer in InterviewQuestionsResponse makes this explicit.
"""

from __future__ import annotations

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models import InterviewQuestion, Job, QuestionProvenance
from app.schemas import InterviewQuestionOut, InterviewQuestionsResponse


async def get_interview_questions(job: Job, db: AsyncSession) -> InterviewQuestionsResponse:
    """
    Fetch stored questions and optionally generate AI practice questions.

    Database questions are split by provenance.
    Gemini questions are generated only if the AI service is available.
    """
    # ── Load stored questions for this job ────────────────────────────────────
    result = await db.execute(
        select(InterviewQuestion).where(
            (InterviewQuestion.job_id == job.id) |
            (InterviewQuestion.company_id == job.company_id)
        ).order_by(InterviewQuestion.created_at.desc())
    )
    all_questions = result.scalars().all()

    source_backed = [q for q in all_questions if q.provenance == QuestionProvenance.source_backed]
    ai_stored = [q for q in all_questions if q.provenance == QuestionProvenance.ai_generated]
    unverified = [q for q in all_questions if q.provenance == QuestionProvenance.unverified]

    # ── Optionally generate AI practice questions ─────────────────────────────
    ai_live: list[InterviewQuestionOut] = []
    if not ai_stored:   # only generate if none are cached
        try:
            from app.integrations.gemini_client import generate_interview_questions
            ai_live = await generate_interview_questions(job)
        except Exception:
            pass  # AI unavailable — no generated questions; that is fine

    ai_combined = [_to_out(q) for q in ai_stored] + ai_live

    disclaimer = (
        "SOURCE-BACKED questions are drawn from publicly referenced sources and include a citation. "
        "AI-GENERATED questions are practice questions created by Gemini based on the job description — "
        "they are NOT confirmed historical interview questions and have not been verified. "
        "Treat them as additional study material only."
    )

    return InterviewQuestionsResponse(
        job_id=job.id,
        source_backed=[_to_out(q) for q in source_backed],
        ai_generated=ai_combined,
        unverified=[_to_out(q) for q in unverified],
        disclaimer=disclaimer,
    )


def _to_out(q: InterviewQuestion) -> InterviewQuestionOut:
    return InterviewQuestionOut(
        id=q.id,
        role=q.role,
        question_text=q.question_text,
        question_category=q.question_category,
        provenance=q.provenance,
        source_url=q.source_url,
        year=q.year,
    )
